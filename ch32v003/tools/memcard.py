"""memcard.py: a card image -> C, for a deck with no SD card (the PY32F030's MEMCARD build).

    ch32v003/tools/memcard.py build/py32fw/sd.img -o build/py32fw/memcard.c

Keeps only the 512-byte sectors that aren't all zero (a fresh FAT32 image is nearly all
zeros), sorted by sector number; the firmware's emulated card (sim/emu/sd_emu.c) serves those
from flash and zeros for the rest.
"""
import argparse, os

ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument("image")
ap.add_argument("-o", "--out", required=True)
a = ap.parse_args()

# Walk only the image's data regions (it's sparse: 2 GB, almost all holes).
keep, size = [], os.path.getsize(a.image)
with open(a.image, "rb") as img:
    fd, pos = img.fileno(), 0
    while pos < size:
        try:
            start = os.lseek(fd, pos, os.SEEK_DATA); end = os.lseek(fd, start, os.SEEK_HOLE)
        except OSError as e:
            if e.errno == 6: break                # ENXIO: only holes from here to the end
            start, end = pos, size                # no hole support: read it all
        except AttributeError:
            start, end = pos, size
        img.seek(start - start % 512)
        for i in range(start // 512, (end + 511) // 512):
            s = img.read(512)
            if any(s): keep.append((i, s))
        pos = end
secs = range(size // 512)
with open(a.out, "w") as f:
    f.write("// Generated by tools/memcard.py from %s: %d of %d sectors (the rest are zero).\n"
            % (a.image, len(keep), len(secs)))
    f.write("#include <stdint.h>\n")
    f.write("const uint32_t memcard_blocks = %du;\n" % len(secs))
    f.write("const uint16_t memcard_count = %du;\n" % len(keep))
    f.write("const uint32_t memcard_lba[] = {%s};\n" % ", ".join(str(i) for i, _ in keep))
    f.write("const uint8_t memcard_data[][512] = {\n")
    for _, s in keep:
        f.write("{" + ",".join(str(b) for b in s) + "},\n")
    f.write("};\n")
print(f"{a.out}: {len(keep)} sectors, {len(keep) * 516 / 1024:.1f} KB of flash")
