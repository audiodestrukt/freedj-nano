"""extract_fonts.py: copy a few u8g2 fonts into components/nano/src/fonts.cpp.

    tools/extract_fonts.py [path/to/u8g2/csrc/u8g2_fonts.c]

The UI draws u8g2's compressed bitmap fonts itself (gfx.cpp), so the portable core
needs the font data but not the u8g2 library. Only the X11 Adobe Helvetica set is
used: freely redistributable with its copyright notice, which is kept below.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "firmware/managed_components/u8g2/csrc/u8g2_fonts.c")
FONTS = {   # our name: u8g2 name
    "kHelvR10": "u8g2_font_helvR10_tr",
    "kHelvB12": "u8g2_font_helvB12_tr",
    "kHelvB14": "u8g2_font_helvB14_tr",
    "kHelvB24Num": "u8g2_font_helvB24_tn",   # digits and + , - . / :
}

src = open(SRC, encoding="latin-1").read()
out = ["// SPDX-FileCopyrightText: 1984, 1987 Adobe Systems Incorporated; 1988, 1991 Digital Equipment Corporation",
       "// SPDX-License-Identifier: X11 AND GPL-3.0-or-later",
       "// Generated by tools/extract_fonts.py from u8g2's u8g2_fonts.c (u8g2: BSD-2-Clause).",
       "// Adobe Helvetica bitmap fonts from X11: Copyright (c) 1984, 1987 Adobe Systems Incorporated.",
       "// All Rights Reserved. Copyright (c) 1988, 1991 Digital Equipment Corporation. All Rights Reserved.",
       '#include "nano/fonts.h"', "", "namespace gfx {", ""]
for ours, name in FONTS.items():
    m = re.search(r"const uint8_t " + re.escape(name) + r"\[(\d+)\][^=]*=\s*((?:\s*\"(?:[^\"\\]|\\.)*\")+);", src)
    if not m:
        sys.exit(f"{name} not found in {SRC}")
    lit = "".join(re.findall(r"\"((?:[^\"\\]|\\.)*)\"", m.group(2)))
    data = eval('b"' + lit + '"')                      # C and Python byte-string escapes agree here
    assert len(data) + 1 == int(m.group(1)), (name, len(data), m.group(1))
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    out.append(f"static const uint8_t {ours}Data[] = {{  // {name}, {len(data)} bytes")
    out += [f"    {r}," for r in rows]
    out.append("};")
    out.append(f"const Font {ours} = {{{ours}Data}};")
    out.append("")
out.append("} // namespace gfx")
dst = os.path.join(ROOT, "components/nano/src/fonts.cpp")
open(dst, "w").write("\n".join(out) + "\n")
print("wrote", dst, ", ".join(FONTS))
